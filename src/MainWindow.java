    private void search() {
        String searchInputValue = searchInputField.getText();

        textEditorModel.find(searchInputValue, chbCaseSensivity.isSelected());
        responseTextField.append("\n" + textEditorModel.getMessage() + "\n");
        textEditorModel.requestFocusInWindow();
    }

    private void openFileDialog() {
        File selectedFile = FileChooser.chooseTextFile(this);
        if (selectedFile != null) {
            if (textEditorModel.open(selectedFile)) {
                setApplicationTitle(selectedFile);
            }
            responseTextField.append(textEditorModel.getMessage() + "\n");
        }
    }

    private void setApplicationTitle(File selectedFile) {
        setTitle(selectedFile.getName());
    }

    private void saveAs() {
        File selectedFile = FileChooser.chooseSaveTextFile(this, textEditorModel.getFile());
        if (selectedFile == null) {
            return;
        }

        if (selectedFile.exists()) {
            int answer = InputDialog.showConfirmOverwriteFileDialog(this);
            if (answer != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }
        }

        saveTo(selectedFile);
    }

    private void saveTo(File selectedFile) {
        if (textEditorModel.saveFile(selectedFile)) {
            setApplicationTitle(textEditorModel.getFile());
        }
        responseTextField.append(textEditorModel.getMessage() + "\n");
    }

    private void closeEditor() {
        if (!textEditorModel.isModified()
                || InputDialog.showConfirmExitDialog(this) == javax.swing.JOptionPane.YES_OPTION) {
            dispose();
        }
    }

    private void replace() {
        String searchText = searchInputField.getText();
        String textToReplace = replaceInputField.getText();
        if (searchText.isEmpty()) {
            responseTextField.append("Suchtext darf nicht leer sein.\n");
            return;
        }

        if (textEditorModel.find(searchText, chbCaseSensivity.isSelected())) {
            textEditorModel.replaceSelection(textToReplace);
        } else {
            responseTextField.append(textEditorModel.getMessage() + "\n");
        }
        textEditorModel.requestFocusInWindow();
    }

    private void replaceAll() {
        String searchText = searchInputField.getText();
        String textToReplace = replaceInputField.getText();
        String editorTextContent = textEditorModel.getText();
        String pattern = Pattern.quote(searchText);

        if (searchText.isEmpty()) {
            return;
        }

        if (chbCaseSensivity.isSelected()) {
            pattern = "(?iu)" + pattern;
        }

        editorTextContent = editorTextContent.replaceAll(
                pattern, Matcher.quoteReplacement(textToReplace));

        textEditorModel.setText(editorTextContent);
    }

    private void finishPositionInput() {
        textEditorModelCaretUpdate(null);
        textEditorModel.requestFocusInWindow();
    }
